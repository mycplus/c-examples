static void print_digests(const char *indent, const uint8_t *a, size_t an, const uint8_t *b, size_t bn,
                          int show_md5, int show_sha1)
{
    uint8_t d[SHA256_DIGEST_SIZE];
    char h[2 * SHA256_DIGEST_SIZE + 1];

    if (show_md5) {
        md5(a, an, d);
        digest_to_hex(d, MD5_DIGEST_SIZE, h);
        printf("%sMD5      %s  (input 1)\n", indent, h);
        md5(b, bn, d);
        digest_to_hex(d, MD5_DIGEST_SIZE, h);
        printf("%sMD5      %s  (input 2)\n", indent, h);
    }
    if (show_sha1) {
        sha1(a, an, d);
        digest_to_hex(d, SHA1_DIGEST_SIZE, h);
        printf("%sSHA-1    %s  (input 1)\n", indent, h);
        sha1(b, bn, d);
        digest_to_hex(d, SHA1_DIGEST_SIZE, h);
        printf("%sSHA-1    %s  (input 2)\n", indent, h);
    }
    sha256(a, an, d);
    digest_to_hex(d, SHA256_DIGEST_SIZE, h);
    printf("%sSHA-256  %s  (input 1)\n", indent, h);
    sha256(b, bn, d);
    digest_to_hex(d, SHA256_DIGEST_SIZE, h);
    printf("%sSHA-256  %s  (input 2)\n", indent, h);
}

static uint8_t *read_file(const char *path, size_t *len)
{
    FILE *f = fopen(path, "rb");
    if (f == NULL) {
        fprintf(stderr, "cannot open %s\n", path);
        exit(2);
    }
    uint8_t *buf = malloc(1 << 20);
    if (buf == NULL)
        exit(2);
    *len = fread(buf, 1, 1 << 20, f);
    fclose(f);
    return buf;
}

static size_t count_differences(const uint8_t *a, const uint8_t *b, size_t n)
{
    size_t diff = 0;
    for (size_t i = 0; i < n; ++i)
        if (a[i] != b[i])
            ++diff;
    return diff;
}

int main(int argc, char **argv)
{
    printf("MD5 collision: two %zu-byte inputs that differ in %zu bytes\n", sizeof MD5_COLLISION_A,
           count_differences(MD5_COLLISION_A, MD5_COLLISION_B, sizeof MD5_COLLISION_A));
    printf("  differing offsets:");
    for (size_t i = 0; i < sizeof MD5_COLLISION_A; ++i)
        if (MD5_COLLISION_A[i] != MD5_COLLISION_B[i])
            printf(" %zu", i);
    printf("\n");
    print_digests("  ", MD5_COLLISION_A, sizeof MD5_COLLISION_A, MD5_COLLISION_B, sizeof MD5_COLLISION_B, 1, 0);

    if (argc == 3) {
        size_t an, bn;
        uint8_t *a = read_file(argv[1], &an), *b = read_file(argv[2], &bn);
        printf("\nSHA-1 collision: two %zu-byte inputs", an);
        if (an == bn)
            printf(" that differ in %zu bytes", count_differences(a, b, an));
        printf("\n");
        print_digests("  ", a, an, b, bn, 0, 1);
        free(a);
        free(b);
    }
    return 0;
}
